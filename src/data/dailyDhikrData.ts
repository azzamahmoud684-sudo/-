/**
 * Deterministic daily dhikr based on today's calendar date
 */
export function getDailyDhikrForToday(): DailyDhikrItem {
  const now = new Date();
  // Generate stable seed based on year, month, day
  const dayOfYear = Math.floor(
    (Date.UTC(now.getFullYear(), now.getMonth(), now.getDate()) -
      Date.UTC(now.getFullYear(), 0, 0)) /
      (24 * 60 * 60 * 1000)
  );
  const index = Math.abs(dayOfYear) % DAILY_DHIKR_LIST.length;
  return DAILY_DHIKR_LIST[index];
}

/**
 * Get another random dhikr different from the current one
 */
export function getAnotherRandomDhikr(currentId?: string): DailyDhikrItem {
  const available = DAILY_DHIKR_LIST.filter((item) => item.id !== currentId);
  if (available.length === 0) return DAILY_DHIKR_LIST[0];
  const randomIndex = Math.floor(Math.random() * available.length);
  return available[randomIndex];
}
